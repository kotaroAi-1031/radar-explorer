// Sync the radar's baselines and threads (Markdown) into a generated
// TypeScript module so the Worker can bundle them as static content.
// The source of truth stays in ~/workspace/radar; rerunning this script
// and redeploying is how the bundled copies are refreshed.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const RADAR_DIR = process.env.RADAR_DIR ?? "/home/hatch/workspace/radar";

function collect(subdir) {
  const dir = join(RADAR_DIR, subdir);
  const out = {};
  for (const file of readdirSync(dir).sort()) {
    const m = file.match(/^(q\d)-.*\.md$/);
    if (!m) continue;
    out[m[1]] = readFileSync(join(dir, file), "utf8");
  }
  return out;
}

const baselines = collect("baselines");
const threads = collect("threads");

const banner =
  "// GENERATED by scripts/sync-content.mjs — do not edit by hand.\n" +
  "// Source of truth: ~/workspace/radar/{baselines,threads}/\n";
const body =
  banner +
  `export const BASELINES: Record<string, string> = ${JSON.stringify(baselines, null, 2)};\n` +
  `export const THREADS: Record<string, string> = ${JSON.stringify(threads, null, 2)};\n`;

writeFileSync(new URL("../src/content.generated.ts", import.meta.url), body);
console.log(
  `synced baselines=${Object.keys(baselines).length} threads=${Object.keys(threads).length}`,
);
